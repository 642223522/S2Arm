// 档位梯子判定单测（runtime/src/qladder.c）：喂时间序列，期望按规则手算——
//   两档 0 = 60 帧、1 = 30 帧；窗口 = 局内画面 30 秒；降档：慢帧（> 目标 × 1.5）> 5% 或中位 > 目标 × 1.05；热状态不参与；没有 GPU 读数不降不升；
//   升档：GPU 占比 × 2 < 70% 攒满 2 分钟、离上次换档 ≥ 5 分钟；60 帧档 GPU < 70% 还降 = CPU 跟不上，本局不按余量升回；再试 60 帧回 0 档、清记号
#include "s2a_qladder.h"
#include <stdio.h>
static int bad;
#define CHECK(c, ...) do { if (!(c)) { printf("✗ " __VA_ARGS__); printf("\n"); bad++; } else { printf("✓ " __VA_ARGS__); printf("\n"); } } while (0)
static double T, G;   // 当前时刻（秒）、GPU 忙累计（毫秒）
// 喂 sec 秒、每帧 ms 毫秒；game 局内画面；gpu GPU 忙占比（< 0 = 没有读数，喂 -1）；th 热状态；itv 游戏自设间隔。返回第一次换到的档（-1 没换），*at 换档时刻
static int feed(double sec, double ms, int game, double gpu, int th, int itv, double *at) {
    int got = -1;
    for (double end = T + sec; T < end - 1e-9; ) { T += ms / 1000; if (gpu >= 0) G += ms * gpu;
        int r = s2a_ql_frame((uint64_t)(T * 1e9), game, (uint64_t)(ms * 1e6), gpu >= 0 ? G : -1, th, itv);
        if (r >= 0 && got < 0) { got = r; if (at) *at = T; } }
    return got;
}
static void fresh(void) { s2a_ql_setup(); T = 1000; G = 0; }
int main(void) {
    double at = 0, t0; int r;
    T = 1000; CHECK(feed(60, 50, 1, 0.9, 0, 1, 0) < 0, "没开局（没 setup）：不判");
    fresh();
    CHECK(s2a_ql_tier() == 0 && s2a_ql_fps60(0) && !s2a_ql_fps60(1), "开局 60 帧档；两档：0 放开 60 帧、1 压回 30 帧");
    CHECK(feed(120, 16.667, 1, 0.5, 0, 1, 0) < 0, "60 帧档稳 60 帧 2 分钟：不换档");
    fresh(); r = feed(40, 33.333, 1, 0.9, 0, 1, &at);
    CHECK(r == 1 && s2a_ql_why() == S2A_QL_WHY_FPS && at - 1000 > 29.9 && at - 1000 < 30.1, "60 帧档只跑出 30 帧：满一个窗口（30 秒）那一刻压回 30 帧（实 档 %d，第 %.2f 秒）", r, at - 1000);
    // 每 30 帧里 1 帧 33.3 ms（3.3% 慢帧）、中位 16.7：不降；每 10 帧 1 帧慢（10%）：降
    fresh(); r = -1; for (int i = 0; i < 100 && r < 0; i++) { r = feed(0.4833, 16.667, 1, 0.5, 0, 1, 0); if (r < 0) r = feed(0.0333, 33.333, 1, 0.5, 0, 1, 0); }
    CHECK(r < 0, "慢帧约 3.3%%（每 29 帧 16.7 ms 夹 1 帧 33.3 ms）：不降（实 %d）", r);
    fresh(); r = -1; for (int i = 0; i < 200 && r < 0; i++) { r = feed(0.15, 16.667, 1, 0.5, 0, 1, 0); if (r < 0) r = feed(0.0333, 33.333, 1, 0.5, 0, 1, 0); }
    CHECK(r == 1, "慢帧约 10%%（每 9 帧夹 1 帧 33.3 ms）：压回 30 帧（实 %d）", r);
    fresh(); CHECK(feed(120, 16.667, 1, 0.5, 3, 1, 0) < 0, "热状态 3（危急）、帧率跟得上 2 分钟：不降（热状态不参与）");
    // #1688 没有 GPU 读数：判不了是不是 GPU 跟不上，照玩家选的 60 帧跑——只跑出 30 帧 10 分钟也不降；对照：同样喂数有读数 30 秒就降（上面第 3 项）
    fresh(); r = feed(600, 33.333, 1, -1, 0, 1, 0); CHECK(r < 0 && s2a_ql_tier() == 0, "没有 GPU 读数、60 帧档只跑出 30 帧 10 分钟：不降（实 换档 %d、档 %d）", r, s2a_ql_tier());
    // 升档：降档那一窗 GPU 80%（GPU 是瓶颈，不算 CPU 跟不上）；之后 30 帧跟得上、GPU 20%（× 2 = 40% < 70%）：
    //   余量 2 分钟早攒够，离换档 5 分钟那个窗口升（每窗 901 帧 × 33.333 ms = 30.033 秒，第 10 窗 300.33 秒）
    fresh(); feed(30.01, 33.333, 1, 0.8, 0, 1, &at); t0 = at; CHECK(s2a_ql_tier() == 1 && !s2a_ql_cpu_bound(), "60 帧档 GPU 80%% 降档：压回 30 帧、不算 CPU 跟不上");
    r = feed(320, 33.333, 1, 0.2, 0, 1, &at); CHECK(r == 0 && s2a_ql_why() == S2A_QL_WHY_UP && at - t0 > 299 && at - t0 < 301, "30 帧档余量足：离换档 5 分钟那个窗口升回 60 帧（实 %d，换档后 %.1f 秒）", r, at - t0);
    fresh(); feed(30.01, 33.333, 1, 0.8, 0, 1, 0); CHECK(feed(600, 33.333, 1, 0.4, 0, 1, 0) < 0, "30 帧档 GPU 40%%（× 2 = 80%% ≥ 70%%）：10 分钟不升");
    fresh(); feed(30.01, 33.333, 1, 0.8, 0, 1, 0); CHECK(feed(600, 50, 1, 0.9, 0, 1, 0) < 0 && s2a_ql_tier() == 1, "30 帧档也跟不上（20 帧）：没处可降，不换");
    fresh(); feed(30.01, 33.333, 1, 0.8, 0, 1, 0); r = feed(600, 33.333, 1, -1, 0, 1, 0); CHECK(r < 0 && s2a_ql_tier() == 1, "30 帧档读数没了：不升（实 %d）", r);
    fresh(); CHECK(feed(120, 33.333, 0, 0.9, 0, 1, 0) < 0, "菜单 / 加载（非局内画面）30 帧 2 分钟：不降");
    fresh(); CHECK(feed(120, 33.333, 1, 0.17, 0, 2, 0) < 0, "60 帧档、游戏自设间隔 2（标题 / 过场自己锁 30 帧）、30 帧 2 分钟：不降（游戏自己限的帧，不是跑不动）");
    fresh(); r = feed(40, 50, 1, 0.9, 0, 2, 0); CHECK(r == 1, "60 帧档、游戏自设间隔 2 但只跑出 20 帧（目标 33.3 ms）：照常降（实 %d）", r);
    // CPU 跟不上（11-17 派对游戏 iPad 60 / 30 每 5 分钟来回切）：60 帧档只跑出 48 帧、GPU 30%（< 70%）→ 降、记成 CPU 跟不上；之后 GPU 15% 跑 20 分钟也不升回
    fresh(); r = feed(30.01, 20.833, 1, 0.3, 0, 1, 0);
    CHECK(r == 1 && s2a_ql_cpu_bound(), "60 帧档 48 帧、GPU 30%%：压回 30 帧（实 档 %d）、记成 CPU 跟不上（实 %d）", r, s2a_ql_cpu_bound());
    r = feed(1200, 33.333, 1, 0.15, 0, 1, 0); CHECK(r < 0 && s2a_ql_tier() == 1, "CPU 跟不上压回的 30 帧、GPU 15%% 跑 20 分钟：不升回 60（实 换档 %d、档 %d）", r, s2a_ql_tier());
    // 再试 60 帧（玩家点横幅按钮 / 局中重开 60 帧）：当场回 60 帧档、原因 4；CPU 跟不上的记号清掉——再降一次（GPU 80%）后余量够照常升回
    s2a_ql_retry((uint64_t)(T * 1e9)); CHECK(s2a_ql_tier() == 0 && s2a_ql_why() == S2A_QL_WHY_RETRY && !s2a_ql_cpu_bound(), "再试 60 帧：回 60 帧档、原因 4、清 CPU 跟不上");
    CHECK(feed(120, 16.667, 1, 0.5, 0, 1, 0) < 0, "再试后跑稳 60 帧 2 分钟：不换档");
    feed(30.01, 33.333, 1, 0.8, 0, 1, 0); r = feed(320, 33.333, 1, 0.2, 0, 1, 0); CHECK(r == 0, "再试后又压回（GPU 是瓶颈）、余量够：照常升回 60（实 %d）", r);
    // 不跨局记：新局（setup）一律从 60 帧起
    fresh(); feed(40, 33.333, 1, 0.9, 0, 1, 0); fresh(); CHECK(s2a_ql_tier() == 0, "上一局压回 30 帧，新局：从 60 帧起（实 档 %d）", s2a_ql_tier());
    // 梯子压 / 放 60 帧时要不要告诉玩家（审计 P1-80 原因 4）：期望按「起局 / 玩家自己点的不说、没变不说、没开 60 帧 / 自动化局不说、压了说 4、放开说 0」手推
    { struct { int boot, last, hold, on, un, want; const char *why; } c[] = {
        {1, -1, 0, 1, 0, -1, "起局摆 60 帧档：不说"},
        {1, 1, 0, 1, 0, -1, "玩家点再试 60 帧放开：不说（玩家自己点的）"},
        {0, -1, 1, 1, 0, -1, "还没摆过档（last = -1）：不说"},
        {0, 0, 1, 1, 0, 4, "局中从 60 帧压回原帧率：说原因 4"},
        {0, 1, 0, 1, 0, 0, "局中按余量放开回 60 帧：说已恢复"},
        {0, 1, 1, 1, 0, -1, "压着没变：不说"},
        {0, 0, 1, 0, 0, -1, "玩家没开 60 帧：不说"},
        {0, 0, 1, 1, 1, -1, "自动化局：不说"} };
      for (unsigned i = 0; i < sizeof c / sizeof *c; i++) { int got = s2a_ql_fps_note(c[i].boot, c[i].last, c[i].hold, c[i].on, c[i].un), ok = got == c[i].want;
        bad += !ok; printf("%s 提示 %s：期望 %d → 实 %d\n", ok ? "✓" : "✗", c[i].why, c[i].want, got); } }
    printf("%s t_qladder：%d 项不符\n", bad ? "✗" : "✓", bad);
    return bad ? 1 : 0;
}
